#!/usr/bin/env python3
"""Make src/ca_bundle.c from a PEM CA bundle.

Usage: scripts/gen_ca_bundle.py <cacert.pem> [out.c]

Get a current bundle from the certifi package (Mozilla's CA list):
    pip download --no-deps certifi -d /tmp/certifi
    unzip -p /tmp/certifi/certifi-*.whl certifi/cacert.pem > /tmp/cacert.pem
"""
import sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "src/ca_bundle.c"

certs, cur = [], None
for line in open(src, encoding="ascii"):
    line = line.strip()
    if line == "-----BEGIN CERTIFICATE-----":
        cur = [line]
    elif cur is not None:
        cur.append(line)
        if line == "-----END CERTIFICATE-----":
            certs.append(cur)
            cur = None

with open(out, "w", encoding="ascii") as f:
    f.write("/* Generated by scripts/gen_ca_bundle.py. Do not edit.\n")
    f.write(f" * Mozilla CA list (via certifi): {len(certs)} certificates. MPL-2.0. */\n")
    f.write("#include <stddef.h>\n\n")
    f.write("const char p2f_ca_bundle[] =\n")
    for c in certs:
        for line in c:
            f.write(f'    "{line}\\n"\n')
    f.write("    ;\n\n")
    f.write("/* Includes the NUL byte, as mbedtls_x509_crt_parse() needs for PEM. */\n")
    f.write("const size_t p2f_ca_bundle_len = sizeof(p2f_ca_bundle);\n")

print(f"{out}: {len(certs)} certificates")
